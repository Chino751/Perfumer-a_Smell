create policy settings_public_read
on public.settings for select to anon, authenticated
using (true);

create policy settings_admin_insert
on public.settings for insert to authenticated
with check (
  exists (
    select 1 from public.admin_profiles ap
    where ap.user_id = (select auth.uid()) and ap.is_active
  )
);

create policy settings_admin_update
on public.settings for update to authenticated
using (
  exists (
    select 1 from public.admin_profiles ap
    where ap.user_id = (select auth.uid()) and ap.is_active
  )
)
with check (
  exists (
    select 1 from public.admin_profiles ap
    where ap.user_id = (select auth.uid()) and ap.is_active
  )
);

revoke all on public.admin_profiles, public.perfumes, public.combos, public.settings from public, anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on public.perfumes, public.combos, public.settings to anon;
grant select on public.admin_profiles, public.perfumes, public.combos, public.settings to authenticated;
grant update on public.perfumes, public.combos to authenticated;
grant insert, update on public.settings to authenticated;

